/**
 * Pull every account key referenced by a transaction, including addresses loaded from
 * lookup tables, so a hooked mint touched via an ALT is not missed.
 */
export function accountKeysOf(tx) {
  const keys = [];
  const msgKeys = tx?.transaction?.message?.accountKeys ?? [];
  for (const k of msgKeys) keys.push(typeof k === 'string' ? k : k?.pubkey);
  const loaded = tx?.meta?.loadedAddresses;
  if (loaded) {
    for (const k of loaded.writable ?? []) keys.push(k);
    for (const k of loaded.readonly ?? []) keys.push(k);
  }
  return keys.filter((k) => typeof k === 'string');
}

/**
 * Sample a program's transaction history and return every distinct account key seen,
 * plus the exact slot range covered — that range is what makes the partiality checkable.
 */
export async function sampleProgramTransactions(programId, {
  maxSignatures = 1000,
  maxTransactions = 200,
  cache,
  refreshSignatures = false,
  log = () => {},
} = {}) {
  const signatures = [];
  let before = null;

  while (signatures.length < maxSignatures) {
    const limit = Math.min(1000, maxSignatures - signatures.length);
    // Signature pages are cached too. Without this a re-run would walk a *different*
    // window of history, so the dataset could not be reproduced from the cache and every
    // re-run would miss the transaction cache entirely.
    const cacheKey = `sigs:${programId}:${limit}:${before ?? 'head'}`;
    let page = null;
    if (!refreshSignatures && cache) {
      const hit = await cache.getRpc(cacheKey);
      if (hit) page = hit.result;
    }
    if (page === null) {
      page = await getSignaturesForAddress(programId, { limit, before });
      if (page && cache) await cache.putRpc(cacheKey, page);
    }
    if (!page || page.length === 0) break;
    signatures.push(...page);
    before = page[page.length - 1].signature;
    if (page.length < 1000) break;
  }

  if (signatures.length === 0) {
    log(`[tx-sample] ${programId}: no signature history returned`);
    return {
      programId, signaturesSeen: 0, transactionsFetched: 0,
      slotRange: null, accountKeys: [], failedTransactions: 0,
    };
  }

  const slots = signatures.map((s) => s.slot).filter((s) => typeof s === 'number');
  const slotRange = slots.length ? { min: Math.min(...slots), max: Math.max(...slots) } : null;

  // Sample evenly across the signature window rather than taking only the newest,
  // so the harvest is not dominated by one busy minute.
  const step = Math.max(1, Math.floor(signatures.length / maxTransactions));
  const picked = [];
  for (let i = 0; i < signatures.length && picked.length < maxTransactions; i += step) {
    picked.push(signatures[i]);
  }

  const accountKeys = new Set();
  let failed = 0;
  let fetchedCount = 0;

  for (const sig of picked) {
    const cacheKey = `tx:${sig.signature}`;
    let tx = null;
    const hit = cache ? await cache.getRpc(cacheKey) : null;
    if (hit) {
      tx = hit.result;
    } else {
      try {
        tx = await rpc('getTransaction', [sig.signature, {
          commitment: 'confirmed', maxSupportedTransactionVersion: 0, encoding: 'jsonParsed',
        }], { timeoutMs: 30_000 });
        if (cache) await cache.putRpc(cacheKey, tx);
        fetchedCount++;
      } catch (err) {
        failed++;
        if (err instanceof RpcError && err.isRefusal) {
          log(`[tx-sample] endpoint refuses getTransaction: ${err.message}`);
          break;
        }
        continue;
      }
    }
    if (!tx) { failed++; continue; }
    for (const k of accountKeysOf(tx)) accountKeys.add(k);
  }

  log(`[tx-sample] ${programId}: ${signatures.length} sigs, ${picked.length} txs sampled, ` +
      `${accountKeys.size} distinct accounts, ${failed} tx fetch failures`);

  return {
    programId,
    signaturesSeen: signatures.length,
    transactionsSampled: picked.length,
    transactionsFetched: fetchedCount,
    failedTransactions: failed,
    slotRange,
    accountKeys: [...accountKeys],
  };
}
