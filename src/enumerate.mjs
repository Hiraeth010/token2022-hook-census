/**
 * Decide what an account is, from its raw RPC value.
 *
 * Returns one of:
 *   { kind: 'absent' }              account does not exist
 *   { kind: 'not-token-2022' }      owned by another program
 *   { kind: 'not-a-mint' }          Token-2022 but a token account / multisig
 *   { kind: 'mint', hooked: false } Token-2022 mint with no TransferHook extension
 *   { kind: 'mint', hooked: true, hook, ... }
 *
 * Returns null only when the bytes could not be parsed at all — an unmeasured cell.
 */
export function classifyAccount(value) {
  if (!value) return { kind: 'absent' };
  if (value.owner !== TOKEN_2022_PROGRAM) return { kind: 'not-token-2022', owner: value.owner };

  let data;
  try {
    data = Buffer.from(value.data[0], 'base64');
  } catch {
    return null;
  }

  const parsed = parseMintExtensions(data);
  if (!parsed) return { kind: 'not-a-mint' };

  const base = parseMintBase(data);
  if (!base) return null;

  const hookEntry = parsed.entries.find((e) => e.type === EXT_TRANSFER_HOOK);
  if (!hookEntry) {
    return {
      kind: 'mint', hooked: false, base, extensions: parsed.entries,
      tlvTruncated: parsed.truncated, dataLength: data.length,
    };
  }

  const hook = parseTransferHook(hookEntry.value);
  return {
    kind: 'mint', hooked: true, base, hook, extensions: parsed.entries,
    hookTlvOffset: hookEntry.offset - 4,
    tlvTruncated: parsed.truncated, dataLength: data.length,
  };
}

