/**
 * enumerate.mjs — finding hooked mints.
 *
 * Enumeration is the hard part of this census and the honest answer is that exactly one
 * method is complete:
 *
 *   A. gpa-full          getProgramAccounts over Token-2022, every mint that has extensions.
 *                        COMPLETE by construction. Most public RPCs refuse it.
 *   B. gpa-offset-sweep  getProgramAccounts filtered on the TransferHook TLV header at a
 *                        fixed byte offset. Cheaper, still GPA. Complete only for mints
 *                        whose hook TLV lands on one of the swept offsets.
 *   C. tx-sample         Sample a program's transaction history, harvest every account key
 *                        seen, and test each one. Coverage is whatever share of traffic we
 *                        sampled, over a slot range we record exactly.
 *   D. seed-verify       Test an explicit candidate list. Coverage is the list.
 *   E. jupiter-verified  Take the Token-2022 subset of a public token list and check every
 *                        member. COMPLETE for that named population — a real denominator —
 *                        but that population is curated and is not the chain. (jupiter.mjs)
 *   F. gpa-hook-program  getProgramAccounts against a KNOWN HOOK PROGRAM, which public
 *                        endpoints do serve even though they refuse it for Token-2022, then
 *                        mine embedded pubkeys from its accounts.
 *
 * B, C, D, E and F are all PARTIAL with respect to mainnet and are labelled as such. None of
 * them can ever justify "there are N hooked mints on mainnet" — only A can. E can justify
 * "N of the M Token-2022 mints in <named list>", which is a different and weaker claim.
 */

import {
  getMultipleAccounts, getProgramAccountsOrThrow, getSignaturesForAddress,
  rpc, RpcError,
} from './rpc.mjs';
import { b58encode } from './crypto.mjs';
import {
  parseMintExtensions, parseTransferHook, parseMintBase,
  EXT_TRANSFER_HOOK, TOKEN_2022_PROGRAM, ACCOUNT_TYPE_OFFSET, TLV_START_OFFSET,
} from './tlv.mjs';

/** memcmp `bytes` are base58, so encode the raw filter bytes rather than hardcoding strings. */
export const MINT_ACCOUNT_TYPE_B58 = b58encode(Uint8Array.from([1]));

/** TLV header for TransferHook: type=14 (u16 LE), length=64 (u16 LE). */
export const TRANSFER_HOOK_TLV_HEADER = Uint8Array.from([14, 0, 64, 0]);
export const TRANSFER_HOOK_TLV_HEADER_B58 = b58encode(TRANSFER_HOOK_TLV_HEADER);

/**
 * Byte sizes of the mint-side extensions that can precede TransferHook in the TLV region.
 * Used to generate candidate offsets for method B. Fixed-size extensions only — a mint
 * carrying a variable-length extension (TokenMetadata) *before* its hook cannot be reached
 * by an offset sweep, which is one reason B is partial.
 */
export const MINT_EXTENSION_SIZES = {
  1: 108,  // TransferFeeConfig
  3: 32,   // MintCloseAuthority
  4: 65,   // ConfidentialTransferMint
  6: 1,    // DefaultAccountState
  9: 0,    // NonTransferable
  10: 24,  // InterestBearingConfig
  12: 32,  // PermanentDelegate
  16: 129, // ConfidentialTransferFeeConfig
  18: 64,  // MetadataPointer
  20: 64,  // GroupPointer
  21: 72,  // TokenGroup
  22: 64,  // GroupMemberPointer
  23: 72,  // TokenGroupMember
  25: 24,  // ScaledUiAmount
  26: 1,   // Pausable
};

/**
 * Candidate byte offsets at which a TransferHook TLV header can begin, assuming every
 * preceding extension is fixed-size. Generated by walking all subsets up to `maxDepth`
 * preceding extensions, deduplicated and sorted.
 */
export function candidateHookOffsets(maxDepth = 3) {
  const sizes = Object.values(MINT_EXTENSION_SIZES).map((s) => s + 4); // +4 TLV header
  const offsets = new Set([TLV_START_OFFSET]);
  let frontier = [TLV_START_OFFSET];
  for (let depth = 0; depth < maxDepth; depth++) {
    const next = [];
    for (const base of frontier) {
      for (const s of sizes) {
        const o = base + s;
        if (!offsets.has(o)) { offsets.add(o); next.push(o); }
      }
    }
    frontier = next;
  }
  return [...offsets].sort((a, b) => a - b);
}

