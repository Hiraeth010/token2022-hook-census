// Candidate testing (shared by every method)
// ---------------------------------------------------------------------------

/**
 * Fetch and classify a set of addresses, using the cache and batching 100 per RPC call.
 * Returns `{ results, fetched, cached, failed }`. Addresses whose fetch failed land in
 * `failed` and are NOT recorded as "no hook" — an unfetched account is unmeasured.
 */
export async function checkCandidates(addresses, { cache, log = () => {}, batchSize = 100 } = {}) {
  const unique = [...new Set(addresses)];
  const results = new Map();
  const failed = [];
  let fetched = 0;
  let cachedCount = 0;

  const toFetch = [];
  for (const addr of unique) {
    const hit = cache ? await cache.getAccount(addr) : null;
    if (hit) {
      cachedCount++;
      results.set(addr, { classification: classifyAccount(hit.value), slot: hit.slot, fromCache: true });
    } else {
      toFetch.push(addr);
    }
  }

  for (let i = 0; i < toFetch.length; i += batchSize) {
    const batch = toFetch.slice(i, i + batchSize);
    const res = await getMultipleAccounts(batch);
    if (!res) {
      failed.push(...batch);
      log(`  batch of ${batch.length} failed; recorded as unmeasured`);
      continue;
    }
    for (let j = 0; j < batch.length; j++) {
      const addr = batch[j];
      const value = res.values[j] ?? null;
      if (cache) await cache.putAccount(addr, value, res.slot);
      results.set(addr, { classification: classifyAccount(value), slot: res.slot, fromCache: false });
      fetched++;
    }
    log(`  checked ${Math.min(i + batchSize, toFetch.length)}/${toFetch.length} candidates`);
  }

  return { results, fetched, cached: cachedCount, failed };
}

