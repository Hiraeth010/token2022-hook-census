/**
 * Probe whether this endpoint will serve getProgramAccounts on Token-2022 at all.
 * Returns `{ available: true }` or `{ available: false, reason, refusal }`.
 * We ask for a zero-length dataSlice so the probe is as cheap as the endpoint allows.
 */
export async function probeGpa() {
  try {
    await getProgramAccountsOrThrow(TOKEN_2022_PROGRAM, {
      dataSlice: { offset: 0, length: 0 },
      filters: [
        { memcmp: { offset: ACCOUNT_TYPE_OFFSET, bytes: MINT_ACCOUNT_TYPE_B58 } },
        { memcmp: { offset: TLV_START_OFFSET, bytes: TRANSFER_HOOK_TLV_HEADER_B58 } },
      ],
    }, { timeoutMs: 30_000, retries: 0 });
    return { available: true };
  } catch (err) {
    return {
      available: false,
      reason: err.message,
      refusal: err instanceof RpcError ? err.isRefusal : false,
    };
  }
}

/**
 * Method A: every Token-2022 mint that carries extensions, parsed locally for a hook.
 * This is the only complete method. Returns null if the endpoint refuses it.
 */
export async function gpaFullMintScan({ cache, log = () => {} } = {}) {
  log('[gpa-full] requesting every Token-2022 mint with extensions...');
  let accounts;
  try {
    accounts = await getProgramAccountsOrThrow(TOKEN_2022_PROGRAM, {
      filters: [{ memcmp: { offset: ACCOUNT_TYPE_OFFSET, bytes: MINT_ACCOUNT_TYPE_B58 } }],
    }, { timeoutMs: 300_000 });
  } catch (err) {
    log(`[gpa-full] unavailable: ${err.message}`);
    return null;
  }

  const hooked = [];
  let scanned = 0;
  for (const acc of accounts) {
    scanned++;
    const value = acc.account;
    if (cache) await cache.putAccount(acc.pubkey, value, null);
    const c = classifyAccount(value);
    if (c?.kind === 'mint' && c.hooked) hooked.push({ mint: acc.pubkey, classification: c });
  }
  log(`[gpa-full] scanned ${scanned} mints, ${hooked.length} carry a TransferHook`);
  return { method: 'gpa-full', complete: true, scanned, hooked };
}

/**
 * Method B: one GPA per candidate TLV offset, filtered to the TransferHook header bytes.
 * Complete only for mints whose hook sits at a swept offset; the swept list is returned
 * so the output can state exactly what was covered.
 */
export async function gpaOffsetSweep({ cache, maxDepth = 2, log = () => {} } = {}) {
  const offsets = candidateHookOffsets(maxDepth);
  log(`[gpa-sweep] sweeping ${offsets.length} candidate hook offsets`);

  const hooked = [];
  const offsetsCovered = [];
  const offsetsFailed = [];

  for (const offset of offsets) {
    try {
      const accounts = await getProgramAccountsOrThrow(TOKEN_2022_PROGRAM, {
        filters: [
          { memcmp: { offset: ACCOUNT_TYPE_OFFSET, bytes: MINT_ACCOUNT_TYPE_B58 } },
          { memcmp: { offset, bytes: TRANSFER_HOOK_TLV_HEADER_B58 } },
        ],
      }, { timeoutMs: 120_000, retries: 1 });
      offsetsCovered.push(offset);
      for (const acc of accounts) {
        if (cache) await cache.putAccount(acc.pubkey, acc.account, null);
        const c = classifyAccount(acc.account);
        if (c?.kind === 'mint' && c.hooked) hooked.push({ mint: acc.pubkey, classification: c });
      }
      if (accounts.length) log(`[gpa-sweep] offset ${offset}: ${accounts.length} hits`);
    } catch (err) {
      offsetsFailed.push({ offset, reason: err.message });
      if (err instanceof RpcError && err.isRefusal) {
        log(`[gpa-sweep] endpoint refuses GPA; aborting sweep`);
        break;
      }
    }
  }

  if (offsetsCovered.length === 0) return null;
  return {
    method: 'gpa-offset-sweep',
    complete: false,
    offsetsSwept: offsetsCovered,
    offsetsFailed,
    hooked: dedupeByMint(hooked),
  };
}

function dedupeByMint(rows) {
  const seen = new Map();
  for (const r of rows) if (!seen.has(r.mint)) seen.set(r.mint, r);
  return [...seen.values()];
}

// ---------------------------------------------------------------------------
// Method E — getProgramAccounts against a hook program (not Token-2022)
// ---------------------------------------------------------------------------

/**
 * Slide a 32-byte window across an account's data and return every window that could be a
 * pubkey. A hook program's own accounts (per-mint config, whitelists, position records)
 * almost always embed the mint they belong to, but at an offset that varies by program, so
 * we do not guess the layout — we take every alignment and let the on-chain check decide.
 *
 * All-zero windows are skipped: they decode to the System Program and are never a mint.
 */
export function pubkeyWindows(data, { stride = 1 } = {}) {
  const b = Buffer.isBuffer(data) ? data : Buffer.from(data);
  const out = new Set();
  for (let o = 0; o + 32 <= b.length; o += stride) {
    const w = b.subarray(o, o + 32);
    let allZero = true;
    for (let i = 0; i < 32; i++) if (w[i] !== 0) { allZero = false; break; }
    if (allZero) continue;
    out.add(b58encode(w));
  }
  return out;
}

/**
 * Enumerate a hook program's accounts and harvest embedded pubkey candidates.
 *
 * Public endpoints refuse getProgramAccounts on Token-2022 but DO serve it for ordinary
 * custom programs, so this works where the Token-2022 scan does not. It enumerates the
 * accounts of ONE hook program — complete for that program's account set, and silent about
 * every mint whose hook program stores no reference to it.
 *
 * Large programs hit `-32012 scan aborted: accumulated scan results exceeded the limit`;
 * that is reported, not swallowed.
 */
export async function gpaHookProgramCandidates(hookProgramId, {
  cache, stride = 1, maxCandidates = 20_000, dataSliceLength = 512, log = () => {},
} = {}) {
  const cacheKey = `gpa-hook:${hookProgramId}`;
  let accounts = null;

  if (cache) {
    const hit = await cache.getRpc(cacheKey);
    if (hit) accounts = hit.result;
  }

  if (accounts === null) {
    try {
      // A hook program can own a lot of data — one of these returned a response large
      // enough to blow Node's 512MB max string length while parsing. Cap each account
      // with a dataSlice: we only need the leading bytes to mine embedded pubkeys, and
      // an unbounded fetch fails outright instead of returning less.
      accounts = await getProgramAccountsOrThrow(hookProgramId, {
        dataSlice: { offset: 0, length: dataSliceLength },
      }, { timeoutMs: 120_000, retries: 1 });
      if (cache) await cache.putRpc(cacheKey, accounts);
    } catch (err) {
      const scanLimit = /-32012|scan aborted|exceeded the limit/i.test(err.message);
      const tooLarge = /longer than|0x1fffffe8|allowance|413/i.test(err.message);
      log(`[gpa-hook] ${hookProgramId}: ${scanLimit ? 'scan limit exceeded' : tooLarge ? 'response too large / quota' : 'unavailable'} — ${err.message}`);
      return {
        hookProgramId, available: false, scanLimitExceeded: scanLimit, responseTooLarge: tooLarge,
        reason: err.message, accountsSeen: 0, candidates: [], truncated: false,
      };
    }
  }

  const candidates = new Set();
  let truncated = false;
  for (const acc of accounts) {
    let data;
    try { data = Buffer.from(acc.account.data[0], 'base64'); } catch { continue; }
    for (const k of pubkeyWindows(data, { stride })) {
      if (candidates.size >= maxCandidates) { truncated = true; break; }
      candidates.add(k);
    }
    if (truncated) break;
  }

  log(`[gpa-hook] ${hookProgramId}: ${accounts.length} program accounts, ${candidates.size} distinct pubkey candidates${truncated ? ' (capped)' : ''}`);

  return {
    hookProgramId,
    available: true,
    scanLimitExceeded: false,
    accountsSeen: accounts.length,
    candidates: [...candidates],
    truncated,
  };
}

